/**
 * Root theme for the FlowDroid UI.
 *
 *  - On Android 12+ we use the system dynamic palette so the app blends with the user's
 *    wallpaper choice.
 *  - On older platforms we fall back to the static neutral palette defined above.
 */
@Composable
fun FlowDroidTheme(
    useDarkTheme: Boolean = isSystemInDarkTheme(),
    useDynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        useDynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val ctx = LocalContext.current
            if (useDarkTheme) dynamicDarkColorScheme(ctx) else dynamicLightColorScheme(ctx)
        }
        useDarkTheme -> StaticDarkColorScheme
        else -> StaticLightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content,
    )
}
